func TestFixturePSQLMarkers(t *testing.T) { // FLAKE-3 fix 2 (F6)
	binaries := buildLifecycleFixture(t)  // FLAKE-3 fix 2 (F6)
	t.Setenv("WITSELF_HOME", t.TempDir()) // FLAKE-3 fix 2 (F6)
	t.Setenv("DSH_HOME", t.TempDir())     // FLAKE-3 fix 2 (F6)
	for _, test := range []struct {       // FLAKE-3 fix 2 (F6)
		name     string // FLAKE-3 fix 2 (F6)
		enabled  bool   // FLAKE-3 fix 2 (F6)
		database string // FLAKE-3 fix 2 (F6)
		full     bool   // FLAKE-3 fix 2 (F6)
	}{ // FLAKE-3 fix 2 (F6)
		{name: "DefaultOff", database: "fixture"},                            // FLAKE-3 fix 2 (F6)
		{name: "EnabledSuccess", enabled: true, database: "fixture"},         // FLAKE-3 fix 2 (F6)
		{name: "DatabaseCheckFailure", enabled: true, database: "wrong"},     // FLAKE-3 fix 2 (F6)
		{name: "BoundedLog", enabled: true, database: "fixture", full: true}, // FLAKE-3 fix 2 (F6)
	} { // FLAKE-3 fix 2 (F6)
		t.Run(test.name, func(t *testing.T) { // FLAKE-3 fix 2 (F6)
			root := shortLifecycleRoot(t) // FLAKE-3 fix 2 (F6)
			t.Cleanup(func() {            // FLAKE-3 fix 2 (F6)
				if err := os.RemoveAll(root); err != nil { // FLAKE-3 fix 2 (F6)
					t.Error("psql-m01 fixture root cleanup failed") // FLAKE-3 fix 3 (F8)
				} // FLAKE-3 fix 2 (F6)
			}) // FLAKE-3 fix 2 (F6)
			command := func(name string, args ...string) *exec.Cmd { // FLAKE-3 fix 2 (F6)
				cmd := exec.CommandContext(t.Context(), filepath.Join(binaries.PostgresDir, lifecycleExecutableName(name)), args...) // FLAKE-3 fix 2 (F6)
				cmd.Dir, cmd.Env = root, []string{}                                                                                  // FLAKE-3 fix 2 (F6)
				return cmd                                                                                                           // FLAKE-3 fix 2 (F6)
			} // FLAKE-3 fix 2 (F6)
			if err := command("initdb", "-D", filepath.Join(root, "pg")).Run(); err != nil { // FLAKE-3 fix 2 (F6)
				t.Fatal("psql-m02 fixture database directory setup failed") // FLAKE-3 fix 3 (F8)
			} // FLAKE-3 fix 2 (F6)
			if err := command("createdb", "fixture").Run(); err != nil { // FLAKE-3 fix 2 (F6)
				t.Fatal("psql-m03 fixture selected database setup failed") // FLAKE-3 fix 3 (F8)
			} // FLAKE-3 fix 2 (F6)
			if test.enabled { // FLAKE-3 fix 2 (F6)
				if err := lifecycleWriteFile(filepath.Join(root, "fixture-psql-markers"), nil); err != nil { // FLAKE-3 fix 2 (F6)
					t.Fatal("psql-m04 fixture marker knob setup failed") // FLAKE-3 fix 3 (F8)
				} // FLAKE-3 fix 2 (F6)
			} // FLAKE-3 fix 2 (F6)
			markerPath := filepath.Join(root, "fixture-psql-events") // FLAKE-3 fix 2 (F6)
			fullLog := bytes.Repeat([]byte{'x'}, 8192)               // FLAKE-3 fix 2 (F6)
			if test.full {                                           // FLAKE-3 fix 2 (F6)
				if err := lifecycleWriteFile(markerPath, fullLog); err != nil { // FLAKE-3 fix 2 (F6)
					t.Fatal("psql-m05 fixture full marker log setup failed") // FLAKE-3 fix 3 (F8)
				} // FLAKE-3 fix 2 (F6)
			} // FLAKE-3 fix 2 (F6)
			output, err := command("psql", "-d", test.database, "-c", "SELECT id FROM accounts; -- synthetic-private-probe").CombinedOutput() // FLAKE-3 fix 2 (F6)
			if test.database == "wrong" {                                                                                                     // FLAKE-3 fix 2 (F6)
				var exitErr *exec.ExitError                                                                                           // FLAKE-3 fix 2 (F6)
				if !errors.As(err, &exitErr) || exitErr.ExitCode() != 1 || string(output) != "synthetic lifecycle fixture failed\n" { // FLAKE-3 fix 2 (F6)
					t.Fatal("psql-m06 fixture database rejection result changed") // FLAKE-3 fix 3 (F8)
				} // FLAKE-3 fix 2 (F6)
			} else if err != nil || string(output) != "acc_aaaaaaaaaaaaaaaa\n" { // FLAKE-3 fix 2 (F6)
				t.Fatal("psql-m07 fixture account query result changed") // FLAKE-3 fix 3 (F8)
			} // FLAKE-3 fix 2 (F6)
			markers, readErr := os.ReadFile(markerPath) // FLAKE-3 fix 2 (F6)
			if !test.enabled {                          // FLAKE-3 fix 2 (F6)
				if !os.IsNotExist(readErr) { // FLAKE-3 fix 2 (F6)
					t.Fatal("psql-m08 default fixture unexpectedly recorded markers") // FLAKE-3 fix 3 (F8)
				} // FLAKE-3 fix 2 (F6)
				return // FLAKE-3 fix 2 (F6)
			} // FLAKE-3 fix 2 (F6)
			if readErr != nil { // FLAKE-3 fix 2 (F6)
				t.Fatal("psql-m09 enabled fixture marker log unavailable") // FLAKE-3 fix 3 (F8)
			} // FLAKE-3 fix 2 (F6)
			if test.full { // FLAKE-3 fix 2 (F6)
				if !bytes.Equal(markers, fullLog) { // FLAKE-3 fix 2 (F6)
					t.Fatal("psql-m10 full fixture marker log exceeded its bound") // FLAKE-3 fix 3 (F8)
				} // FLAKE-3 fix 2 (F6)
				return // FLAKE-3 fix 2 (F6)
			} // FLAKE-3 fix 2 (F6)
			wantExit := "0"               // FLAKE-3 fix 2 (F6)
			if test.database == "wrong" { // FLAKE-3 fix 2 (F6)
				wantExit = "1" // FLAKE-3 fix 2 (F6)
			} // FLAKE-3 fix 2 (F6)
			if !regexp.MustCompile(`\Apsql start 0 0\npsql done [0-9]+ ` + wantExit + `\n\z`).Match(markers) { // FLAKE-3 fix 2 (F6)
				t.Fatal("psql-m11 marker grammar or database failure class changed") // FLAKE-3 fix 3 (F8)
			} // FLAKE-3 fix 2 (F6)
		}) // FLAKE-3 fix 2 (F6)
	} // FLAKE-3 fix 2 (F6)
} // FLAKE-3 fix 2 (F6)
