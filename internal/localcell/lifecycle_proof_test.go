var postgres16Version = regexp.MustCompile(`^postgres \(PostgreSQL\) 16\.[0-9]+(?:\s|$)`)

// Shared with the host contract so weakening the native round-trip sample is
// detected even when no PostgreSQL distribution is configured.
const lifecycleUnicodeName = "Local café Ελληνικά 日本語 🐘"

func postgresEncodingAndLocaleMatch(encoding, collate, ctype string) bool {
	return encoding == "UTF8" && collate == "C" && ctype == "C"
}

func requirePostgres16(t *testing.T, directory string) {
	t.Helper()
	cmd := exec.CommandContext(t.Context(), filepath.Join(directory, lifecycleExecutableName("postgres")), "--version")
	release, err := localcell.ConfigurePostgresProofCommand(cmd)
	if err != nil {
		t.Fatal("cannot restrict PostgreSQL version proof command")
	}
	defer release()
	output, err := cmd.Output()
	if err != nil || !postgres16Version.Match(bytes.TrimSpace(output)) {
		t.Fatal("native lifecycle proof requires PostgreSQL major 16")
	}
}

func TestRealLifecycleRequiresPostgres16(t *testing.T) {
	for _, tc := range []struct {
		version string
		want    bool
	}{
		{"postgres (PostgreSQL) 16.15", true},
		{"postgres (PostgreSQL) 16.4 (EDB)", true},
		{"postgres (PostgreSQL) 17.1", false},
		{"postgres (PostgreSQL) 116.1", false},
		{"postgres (PostgreSQL) 16", false},
		{"postgres (PostgreSQL) 16.1unexpected", false},
	} {
		if postgres16Version.MatchString(tc.version) != tc.want {
			t.Error("PostgreSQL proof major guard accepted the wrong version shape")
		}
	}
}

func lifecycleDSN(t *testing.T, root string, manifest *localcell.Manifest) string {
	t.Helper()
	// This is a password generated by this test's disposable cell, never an
	// ambient home credential. Keep it and the resulting DSN out of diagnostics.
	password, err := os.ReadFile(filepath.Join(root, "run", "postgres.password"))
	if err != nil {
		t.Fatal("cannot read test-owned PostgreSQL password")
	}
	dsn := url.URL{Scheme: "postgres", User: url.UserPassword(manifest.Role, strings.TrimSpace(string(password))), Host: net.JoinHostPort("127.0.0.1", strconv.Itoa(manifest.Ports.Postgres)), Path: "/" + manifest.Database, RawQuery: "sslmode=disable"}
	return dsn.String()
}

func assertPostgresEncodingAndUnicode(t *testing.T, root string, manifest *localcell.Manifest) {
	t.Helper()
	if !postgres16Version.MatchString(manifest.PostgreSQLVersion) {
		t.Fatal("manifest did not record PostgreSQL major 16")
	}
	dsn := lifecycleDSN(t, root, manifest)
	db, err := pgx.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatal("cannot connect to test-owned encoding proof database")
	}
	defer func() { _ = db.Close(t.Context()) }()
	var encoding, collate, ctype string
	var version int
	err = db.QueryRow(t.Context(), `SELECT pg_encoding_to_char(encoding), datcollate, datctype, current_setting('server_version_num')::int FROM pg_database WHERE datname=current_database()`).Scan(&encoding, &collate, &ctype, &version)
	if err != nil || !postgresEncodingAndLocaleMatch(encoding, collate, ctype) || version/10000 != 16 {
		t.Fatal("created database must use PostgreSQL 16, UTF8 encoding and C collation/ctype")
	}
	st, err := store.Open(t.Context(), dsn)
	if err != nil {
		t.Fatal("cannot open test-owned Unicode proof store")
	}
	defer st.Close()
	owner, err := st.EnsureRootOperator(t.Context(), manifest.AccountID)
	if err != nil {
		t.Fatal("cannot resolve test-owned root operator")
	}
	ttl := time.Hour
	bearer, _, _, err := st.CreateOperatorToken(t.Context(), manifest.AccountID, owner, "lifecycle Unicode proof", &ttl)
	if err != nil {
		t.Fatal("cannot mint test-owned Unicode proof credential")
	}
	// Writes and reads both cross the running local HTTP server. A direct SQL
	// read additionally proves this is a persisted row, not a reflected response.
	body, err := json.Marshal(map[string]string{"display_name": lifecycleUnicodeName, "ttl": "1h"})
	if err != nil {
		t.Fatal("cannot encode Unicode proof request")
	}
	var created struct {
		Operator struct {
			ID   string `json:"id"`
			Name string `json:"display_name"`
		} `json:"operator"`
	}
	lifecycleJSON(t, manifest, bearer, http.MethodPost, "/v1/operators", body, &created)
	if created.Operator.ID == "" || created.Operator.Name != lifecycleUnicodeName {
		t.Fatal("Unicode create response did not round trip")
	}
	var listed struct {
		Operators []struct {
			ID   string `json:"id"`
			Name string `json:"display_name"`
		} `json:"operators"`
	}
	lifecycleJSON(t, manifest, bearer, http.MethodGet, "/v1/operators", nil, &listed)
	found := false
	for _, operator := range listed.Operators {
		if operator.ID == created.Operator.ID && operator.Name == lifecycleUnicodeName {
			found = true
		}
	}
	if !found {
		t.Fatal("Unicode row did not round trip through the local server")
	}
	var stored string
	if err := db.QueryRow(t.Context(), `SELECT display_name FROM operators WHERE id=$1 AND account_id=$2`, created.Operator.ID, manifest.AccountID).Scan(&stored); err != nil || stored != lifecycleUnicodeName {
		t.Fatal("Unicode server write was not persisted byte-for-byte")
	}
}

func lifecycleJSON(t *testing.T, manifest *localcell.Manifest, bearer, method, path string, body []byte, out any) {
	t.Helper()
	endpoint := "http://" + net.JoinHostPort("127.0.0.1", strconv.Itoa(manifest.Ports.ServerAPI)) + path
	req, err := http.NewRequestWithContext(t.Context(), method, endpoint, bytes.NewReader(body))
	if err != nil {
		t.Fatal("cannot construct Unicode proof request")
	}
	req.Header.Set("Authorization", "Bearer "+bearer)
	req.Header.Set("Content-Type", "application/json")
	client := &http.Client{Transport: &http.Transport{Proxy: nil}, Timeout: 5 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}
	defer client.CloseIdleConnections()
	response, err := client.Do(req)
	if err != nil {
		t.Fatal("Unicode proof request failed")
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		t.Fatal("Unicode proof request was refused")
	}
	if err := json.NewDecoder(io.LimitReader(response.Body, 1<<20)).Decode(out); err != nil {
		t.Fatal("cannot decode Unicode proof response")
	}
}

type lifecycleProcessWitness struct {
	root    string
	records map[string]localcell.ProcessRecord
}

func newLifecycleProcessWitness(t *testing.T, root string) *lifecycleProcessWitness {
	t.Helper()
	return &lifecycleProcessWitness{root: root, records: make(map[string]localcell.ProcessRecord)}
}

func (w *lifecycleProcessWitness) capture(t *testing.T) {
	t.Helper()
	for _, component := range []string{"postgres", "server", "worker"} {
		data, err := os.ReadFile(filepath.Join(w.root, "run", component+".json"))
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			t.Error("cannot retain cell process cleanup identity")
			continue
		}
		var record localcell.ProcessRecord
		if json.Unmarshal(data, &record) != nil || record.Component != component || record.PID <= 1 || record.StartTime == "" {
			t.Error("invalid cell process cleanup identity")
			continue
		}
		// Retain each incarnation across restart and removal of the on-disk record.
		w.records[fmt.Sprintf("%d:%s", record.PID, record.StartTime)] = record
	}
}

func (w *lifecycleProcessWitness) assertStopped(t *testing.T) {
	t.Helper()
	for _, record := range w.records {
		alive, err := localcell.RecordAliveForTest(record)
		if err != nil {
			t.Errorf("cannot verify %s cleanup identity", record.Component)
		} else if alive {
			t.Errorf("owned %s process survived cell cleanup", record.Component)
		}
	}
}
