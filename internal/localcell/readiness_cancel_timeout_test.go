func cancellationFixtureTimeout(baseline time.Duration) time.Duration { // FLAKE-3 fix 2 (F6)
	// Eight rounds the initial emulated Install spread (6187/919 = 6.73x) up. // FLAKE-3 fix 2 (F6)
	// The five-second floor retains headroom for fast native fixture installs. // FLAKE-3 fix 2 (F6)
	const floor = 5 * time.Second            // FLAKE-3 fix 2 (F6)
	const multiplier = 8                     // FLAKE-3 fix 2 (F6)
	const maximum = time.Duration(1<<63 - 1) // FLAKE-3 fix 2 (F6)
	if baseline <= floor/multiplier {        // FLAKE-3 fix 2 (F6)
		return floor // FLAKE-3 fix 2 (F6)
	} // FLAKE-3 fix 2 (F6)
	if baseline > maximum/multiplier { // FLAKE-3 fix 2 (F6)
		return maximum // FLAKE-3 fix 2 (F6)
	} // FLAKE-3 fix 2 (F6)
	return multiplier * baseline // FLAKE-3 fix 2 (F6)
} // FLAKE-3 fix 2 (F6)
func TestReadinessCancellationTimeoutUsesInstallBaseline(t *testing.T) { // FLAKE-3 fix 2 (F6)
	const maximum = time.Duration(1<<63 - 1) // FLAKE-3 fix 2 (F6)
	for _, test := range []struct {          // FLAKE-3 fix 2 (F6)
		name     string        // FLAKE-3 fix 2 (F6)
		baseline time.Duration // FLAKE-3 fix 2 (F6)
		want     time.Duration // FLAKE-3 fix 2 (F6)
	}{ // FLAKE-3 fix 2 (F6)
		{name: "MinimumNegative", baseline: time.Duration(-1 << 63), want: 5 * time.Second},                             // FLAKE-3 fix 2 (F6)
		{name: "Negative", baseline: -time.Nanosecond, want: 5 * time.Second},                                           // FLAKE-3 fix 2 (F6)
		{name: "Zero", baseline: 0, want: 5 * time.Second},                                                              // FLAKE-3 fix 2 (F6)
		{name: "BelowFloor", baseline: 625*time.Millisecond - time.Nanosecond, want: 5 * time.Second},                   // FLAKE-3 fix 2 (F6)
		{name: "ExactFloor", baseline: 625 * time.Millisecond, want: 5 * time.Second},                                   // FLAKE-3 fix 2 (F6)
		{name: "AboveFloor", baseline: 625*time.Millisecond + time.Nanosecond, want: 5*time.Second + 8*time.Nanosecond}, // FLAKE-3 fix 2 (F6)
		{name: "ShortEmulatedInstall", baseline: 900 * time.Millisecond, want: 7200 * time.Millisecond},                 // FLAKE-3 fix 2 (F6)
		{name: "TypicalEmulatedInstall", baseline: 1500 * time.Millisecond, want: 12 * time.Second},                     // FLAKE-3 fix 2 (F6)
		{name: "LongestInitialInstall", baseline: 6187 * time.Millisecond, want: 49496 * time.Millisecond},              // FLAKE-3 fix 2 (F6)
		{name: "LargestSafeProduct", baseline: maximum / 8, want: maximum - 7*time.Nanosecond},                          // FLAKE-3 fix 2 (F6)
		{name: "FirstOverflow", baseline: maximum/8 + time.Nanosecond, want: maximum},                                   // FLAKE-3 fix 2 (F6)
		{name: "MaximumPositive", baseline: maximum, want: maximum},                                                     // FLAKE-3 fix 2 (F6)
	} { // FLAKE-3 fix 2 (F6)
		t.Run(test.name, func(t *testing.T) { // FLAKE-3 fix 2 (F6)
			if got := cancellationFixtureTimeout(test.baseline); got != test.want { // FLAKE-3 fix 2 (F6)
				t.Fatalf("derived step timeout mismatch: got %s, want %s", got, test.want) // FLAKE-3 fix 2 (F6)
			} // FLAKE-3 fix 2 (F6)
		}) // FLAKE-3 fix 2 (F6)
	} // FLAKE-3 fix 2 (F6)
} // FLAKE-3 fix 2 (F6)
