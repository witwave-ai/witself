func declaredSyncSchemaProjection() (map[string]syncSchemaTable, error) {
	if err := validateSyncSchemaProjection(syncSchemaProjection, syncArchiveTables, syncLocalArchiveExclusions); err != nil {
		return nil, err
	}
	projection := make(map[string]syncSchemaTable, len(syncSchemaProjection))
	for name, table := range syncSchemaProjection {
		table.columns = slices.Clone(table.columns)
		projection[name] = table
	}
	return projection, nil
}

func validateSyncSchemaProjection(projection map[string]syncSchemaTable, portable []syncArchiveTable, exclusions map[string]syncArchiveExclusion) error {
	registered := map[string]bool{syncSchemaVersionTable: true}
	for _, archive := range portable {
		table, ok := projection[archive.name]
		if !ok || registered[archive.name] || len(table.columns) != len(archive.columns) {
			return errSyncSchemaProjection
		}
		registered[archive.name] = true
		for i, column := range table.columns {
			if column.name != archive.columns[i] {
				return errSyncSchemaProjection
			}
		}
	}
	for name := range exclusions {
		if _, ok := projection[name]; !ok || registered[name] {
			return errSyncSchemaProjection
		}
		registered[name] = true
	}
	if len(registered) != len(projection) {
		return errSyncSchemaProjection
	}
	for name, table := range projection {
		if !registered[name] || table.tableType != "BASE TABLE" || len(table.columns) == 0 {
			return errSyncSchemaProjection
		}
		names := make(map[string]bool, len(table.columns))
		previousOrdinal := 0
		for _, column := range table.columns {
			// Domain-base rank is outside the closed projection: these forms
			// cannot be registered until a new owner ruling supports them.
			if column.domainName != "" && column.dataType == "ARRAY" {
				return syncSchemaDifference(name, column.name)
			}
			if column.name == "" || names[column.name] || column.ordinal <= previousOrdinal || column.dataType == "" || column.fullType == "" || column.typeName == "" ||
				(column.domainName == "") != (column.domainBase == "") || column.hasDefault != (column.defaultExpr != "") {
				return errSyncSchemaProjection
			}
			previousOrdinal = column.ordinal
			names[column.name] = true
		}
	}
	return nil
}
